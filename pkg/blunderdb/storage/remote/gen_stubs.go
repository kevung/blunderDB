//go:build ignore

// gen_stubs writes unsupported_gen.go: for every method of a storage.*Store
// interface that the remote backend does not implement by hand, a stub that
// answers *UnsupportedError, plus the Unsupported list naming them all.
//
// Run from this directory: go run gen_stubs.go
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

const (
	storageDir  = ".."
	storagePath = "github.com/kevung/blunderdb/pkg/blunderdb/storage"
	outFile     = "unsupported_gen.go"
)

type method struct {
	iface, name string
	ft          *ast.FuncType
}

func main() {
	fset := token.NewFileSet()
	imports := map[string]string{"storage": storagePath}
	var methods []method
	for _, f := range parseDir(fset, storageDir) {
		for _, im := range f.Imports {
			p, _ := strconv.Unquote(im.Path.Value)
			name := filepath.Base(p)
			if im.Name != nil {
				name = im.Name.Name
			}
			imports[name] = p
		}
		for _, d := range f.Decls {
			gd, ok := d.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, sp := range gd.Specs {
				ts := sp.(*ast.TypeSpec)
				it, ok := ts.Type.(*ast.InterfaceType)
				if !ok || !strings.HasSuffix(ts.Name.Name, "Store") || ts.Name.Name == "Stores" {
					continue
				}
				for _, m := range it.Methods.List {
					ft, ok := m.Type.(*ast.FuncType)
					if !ok || len(m.Names) == 0 {
						fail("%s embeds an interface; teach gen_stubs to follow it", ts.Name.Name)
					}
					methods = append(methods, method{ts.Name.Name, m.Names[0].Name, ft})
				}
			}
		}
	}

	written := map[string]bool{} // "positionStore.Save"
	for _, f := range parseDir(fset, ".") {
		for _, d := range f.Decls {
			fd, ok := d.(*ast.FuncDecl)
			if !ok || fd.Recv == nil {
				continue
			}
			written[recvName(fd.Recv.List[0].Type)+"."+fd.Name.Name] = true
		}
	}

	sort.Slice(methods, func(i, j int) bool {
		if methods[i].iface != methods[j].iface {
			return methods[i].iface < methods[j].iface
		}
		return methods[i].name < methods[j].name
	})

	var body bytes.Buffer
	used := map[string]bool{"context": true}
	var listed []string
	for _, m := range methods {
		recv := lowerFirst(m.iface)
		if written[recv+"."+m.name] {
			continue
		}
		qname := m.iface + "." + m.name
		listed = append(listed, qname)
		params := fieldList(fset, m.ft.Params, used, "_")
		results := m.ft.Results.List
		var sig, ret string
		switch {
		case len(results) == 1 && isSeq2(results[0].Type):
			ix := results[0].Type.(*ast.IndexListExpr)
			sig = typeString(fset, results[0].Type, used)
			ret = fmt.Sprintf("return unsupportedSeq[%s](%q)", typeString(fset, ix.Indices[0], used), qname)
		case isError(results[len(results)-1].Type):
			var names, rets []string
			n := 0
			for _, r := range results[:len(results)-1] {
				k := max(1, len(r.Names))
				for range k {
					nm := fmt.Sprintf("r%d", n)
					n++
					names = append(names, nm+" "+typeString(fset, r.Type, used))
					rets = append(rets, nm)
				}
			}
			if len(names) == 0 {
				sig = "error"
				ret = fmt.Sprintf("return unsupported(%q)", qname)
			} else {
				sig = "(" + strings.Join(names, ", ") + ", err error)"
				ret = fmt.Sprintf("return %s, unsupported(%q)", strings.Join(rets, ", "), qname)
			}
		default:
			fail("%s returns no error and no stream; it cannot be refused", qname)
		}
		fmt.Fprintf(&body, "func (%s) %s(%s) %s {\n\t%s\n}\n\n", recv, m.name, params, sig, ret)
	}

	var out bytes.Buffer
	out.WriteString("// Code generated by gen_stubs.go; DO NOT EDIT.\n\npackage remote\n\nimport (\n")
	var names []string
	for n := range used {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		p, ok := imports[n]
		if !ok {
			fail("unknown package %s", n)
		}
		if filepath.Base(p) == n {
			fmt.Fprintf(&out, "\t%q\n", p)
		} else {
			fmt.Fprintf(&out, "\t%s %q\n", n, p)
		}
	}
	out.WriteString(")\n\n// Unsupported lists the contract methods the /v1 API exposes no route for;\n// each answers *UnsupportedError.\nvar Unsupported = []string{\n")
	for _, q := range listed {
		fmt.Fprintf(&out, "\t%q,\n", q)
	}
	out.WriteString("}\n\n")
	out.Write(body.Bytes())
	src, err := format.Source(out.Bytes())
	if err != nil {
		os.WriteFile(outFile, out.Bytes(), 0o644)
		fail("format: %v", err)
	}
	if err := os.WriteFile(outFile, src, 0o644); err != nil {
		fail("%v", err)
	}
}

func parseDir(fset *token.FileSet, dir string) []*ast.File {
	paths, _ := filepath.Glob(filepath.Join(dir, "*.go"))
	var files []*ast.File
	for _, p := range paths {
		b := filepath.Base(p)
		if strings.HasSuffix(b, "_test.go") || b == outFile || b == "gen_stubs.go" {
			continue
		}
		f, err := parser.ParseFile(fset, p, nil, 0)
		if err != nil {
			fail("%v", err)
		}
		files = append(files, f)
	}
	return files
}

func recvName(e ast.Expr) string {
	if st, ok := e.(*ast.StarExpr); ok {
		e = st.X
	}
	return e.(*ast.Ident).Name
}

func lowerFirst(s string) string { return strings.ToLower(s[:1]) + s[1:] }

func isError(e ast.Expr) bool { id, ok := e.(*ast.Ident); return ok && id.Name == "error" }

func isSeq2(e ast.Expr) bool {
	ix, ok := e.(*ast.IndexListExpr)
	if !ok {
		return false
	}
	sel, ok := ix.X.(*ast.SelectorExpr)
	return ok && sel.Sel.Name == "Seq2"
}

func fieldList(fset *token.FileSet, fl *ast.FieldList, used map[string]bool, name string) string {
	var parts []string
	for _, f := range fl.List {
		k := max(1, len(f.Names))
		for range k {
			parts = append(parts, name+" "+typeString(fset, f.Type, used))
		}
	}
	return strings.Join(parts, ", ")
}

// typeString prints a type as written in package storage, qualifying the
// storage package's own exported names and noting the packages it uses.
func typeString(fset *token.FileSet, e ast.Expr, used map[string]bool) string {
	q := qualify(e, used)
	var b bytes.Buffer
	printer.Fprint(&b, fset, q)
	return b.String()
}

func qualify(e ast.Expr, used map[string]bool) ast.Expr {
	switch t := e.(type) {
	case *ast.Ident:
		if unicode.IsUpper(rune(t.Name[0])) {
			used["storage"] = true
			return &ast.SelectorExpr{X: ast.NewIdent("storage"), Sel: ast.NewIdent(t.Name)}
		}
		return t
	case *ast.SelectorExpr:
		used[t.X.(*ast.Ident).Name] = true
		return t
	case *ast.StarExpr:
		return &ast.StarExpr{X: qualify(t.X, used)}
	case *ast.ArrayType:
		return &ast.ArrayType{Len: t.Len, Elt: qualify(t.Elt, used)}
	case *ast.MapType:
		return &ast.MapType{Key: qualify(t.Key, used), Value: qualify(t.Value, used)}
	case *ast.Ellipsis:
		return &ast.Ellipsis{Elt: qualify(t.Elt, used)}
	case *ast.IndexListExpr:
		ix := &ast.IndexListExpr{X: qualify(t.X, used)}
		for _, i := range t.Indices {
			ix.Indices = append(ix.Indices, qualify(i, used))
		}
		return ix
	case *ast.IndexExpr:
		return &ast.IndexExpr{X: qualify(t.X, used), Index: qualify(t.Index, used)}
	case *ast.FuncType:
		ft := &ast.FuncType{Params: &ast.FieldList{}}
		for _, f := range t.Params.List {
			ft.Params.List = append(ft.Params.List, &ast.Field{Names: f.Names, Type: qualify(f.Type, used)})
		}
		if t.Results != nil {
			ft.Results = &ast.FieldList{}
			for _, f := range t.Results.List {
				ft.Results.List = append(ft.Results.List, &ast.Field{Names: f.Names, Type: qualify(f.Type, used)})
			}
		}
		return ft
	case *ast.InterfaceType, *ast.StructType, *ast.ChanType:
		return t
	default:
		fail("unhandled type %T", e)
		return nil
	}
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "gen_stubs: "+format+"\n", args...)
	os.Exit(1)
}
