// demoDBGz is the sample database for the guided tours, generated by
// scripts/build-demo-db.sh (rerun after every DatabaseVersion bump).
//
//go:embed demo.db.gz
var demoDBGz []byte

// App struct
type App struct {
	ctx context.Context
	// db is used only by jobs that need both the database and Wails events
	// (the gammonNet batch); other App methods stay database-free.
	db *database.Database

	// gnEvalMu/gnEvalCancel govern the Eval panel's at-rest search
	// (gammonnet_eval.go); gnLivePool is its shared searcher.
	gnEvalMu     sync.Mutex
	gnEvalCancel context.CancelFunc
	gnLivePool   gammonNetLivePool

	// gnBatchMu/gnBatchCancel: the same for the batch (gammonnet_batch.go).
	gnBatchMu     sync.Mutex
	gnBatchCancel context.CancelFunc
	// gnBatchDone is closed once the batch has actually stopped (nil when
	// none runs): a cancelled batch still writes its in-flight results, so
	// shutdown must wait on it before closing the database.
	gnBatchDone chan struct{}

	// trainingGen is built once, lazily (it costs megabytes); trainingErr
	// keeps why it failed so later questions refuse by name.
	trainingOnce sync.Once
	trainingGen  *training.Generator
	trainingErr  error

	// startupFilePath is the database the OS passed on the command line (file
	// association), set by run.go; empty on an ordinary launch.
	startupFilePath string

	// folderWatch is the watched folder's loop (watch.go).
	folderWatch folderWatch
}

// NewApp creates a new App application struct.
func NewApp(db *database.Database) *App {
	return &App{db: db}
}

// PrepareDemoDatabase decompresses the sample database to a fresh temporary
// file, for the normal open-database flow, and returns its path.
func (a *App) PrepareDemoDatabase() (string, error) {
	gz, err := gzip.NewReader(bytes.NewReader(demoDBGz))
	if err != nil {
		return "", fmt.Errorf("reading demo database: %w", err)
	}
	defer gz.Close()

	data, err := io.ReadAll(gz)
	if err != nil {
		return "", fmt.Errorf("decompressing demo database: %w", err)
	}

	f, err := os.CreateTemp("", "blunderdb-demo-*.db")
	if err != nil {
		return "", fmt.Errorf("creating temp demo database: %w", err)
	}
	defer f.Close()

	if _, err := f.Write(data); err != nil {
		return "", fmt.Errorf("writing temp demo database: %w", err)
	}
	return f.Name(), nil
}

