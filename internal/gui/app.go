// IsDirectory returns true if the given path is a directory.
func (a *App) IsDirectory(path string) bool {
	info, err := os.Stat(path)
	if err != nil {
		return false
	}
	return info.IsDir()
}

// PathExists reports whether path resolves on disk now. It decides nothing:
// the caller tells a gone path from a transient open failure.
func (a *App) PathExists(path string) bool {
	if path == "" {
		return false
	}
	_, err := os.Stat(path)
	return err == nil
}

// CollectImportableFiles recursively walks dirPath and returns all supported position/match files.
func (a *App) CollectImportableFiles(dirPath string) ([]string, error) {
	var files []string
	err := filepath.Walk(dirPath, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return nil // skip files/dirs we can't access
		}
		if info.IsDir() {
			return nil
		}
		if ingest.IsImportable(path) {
			files = append(files, path)
		}
		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("failed to walk directory: %w", err)
	}
	return files, nil
}

// ReadFileContent reads and returns the content of a file as a string,
