// OpenLogsFolder opens applog.Dir() in the file manager, creating it if
// needed.
func (a *App) OpenLogsFolder() error {
	dir := applog.Dir()
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return newGUIError(CodeInternal, err.Error())
	}
	if err := openFolder(dir); err != nil {
		return newGUIError(CodeInternal, err.Error())
	}
	return nil
}

// ReadLogTail returns the last lines of the log file, oldest first; a missing
// file (nothing logged yet) returns nothing, not an error.
func (a *App) ReadLogTail(lines int) ([]string, error) {
	out, err := applog.TailLines(lines)
	if err != nil {
		return nil, newGUIError(CodeInternal, err.Error())
	}
	return out, nil
}

// openFolder opens dir in the platform's file manager, passing dir as an
// argument, never through a shell.
func openFolder(dir string) error {
	var cmd *exec.Cmd
	switch goruntime.GOOS {
	case "darwin":
		cmd = exec.Command("open", dir)
	case "windows":
		cmd = exec.Command("explorer", dir)
	default:
		cmd = exec.Command("xdg-open", dir)
	}
	return cmd.Run()
}

// CopyImageToClipboard copies a base64 PNG to the clipboard, the fallback
// after the WebView's own write (ADR-0004). If no clipboard works it saves the
// PNG and returns its path ("" = clipboard reached); it errors only when even
// that fails.
func (a *App) CopyImageToClipboard(base64Data string) (string, error) {
	pngData, err := base64.StdEncoding.DecodeString(base64Data)
	if err != nil {
		return "", fmt.Errorf("failed to decode base64 data: %w", err)
	}

	switch goruntime.GOOS {
	case "linux":
		return copyImageLinux(pngData)

	case "darwin":
		// The path travels as an environment variable, never interpolated
		// into the script (a `"` or backslash would break it).
		if err := copyImageViaTempFile(pngData, func(path string) *exec.Cmd {
			cmd := exec.Command("osascript", "-e",
				`set the clipboard to (read (POSIX file (system attribute "BLUNDERDB_CLIPBOARD_PATH")) as «class PNGf»)`)
			cmd.Env = append(os.Environ(), "BLUNDERDB_CLIPBOARD_PATH="+path)
			return cmd
		}); err != nil {
			return saveImageFallback(pngData)
		}
		return "", nil

	case "windows":
		// As on darwin: the path travels as an environment variable.
		if err := copyImageViaTempFile(pngData, func(path string) *exec.Cmd {
			cmd := exec.Command("powershell", "-NoProfile", "-Command",
				`Add-Type -AssemblyName System.Windows.Forms; [System.Windows.Forms.Clipboard]::SetImage([System.Drawing.Image]::FromFile($env:BLUNDERDB_CLIPBOARD_PATH))`)
			cmd.Env = append(os.Environ(), "BLUNDERDB_CLIPBOARD_PATH="+path)
			return cmd
		}); err != nil {
			return saveImageFallback(pngData)
		}
		return "", nil

	default:
		return saveImageFallback(pngData)
	}
}

// copyImageViaTempFile writes the PNG to a temp file and runs the command built
// by buildCmd against it (macOS/Windows clipboard tools read from a file path).
func copyImageViaTempFile(pngData []byte, buildCmd func(path string) *exec.Cmd) error {
	tmpFile, err := os.CreateTemp("", "blunderdb-clipboard-*.png")
	if err != nil {
		return fmt.Errorf("failed to create temp file: %w", err)
	}
	defer os.Remove(tmpFile.Name())
	if _, err := tmpFile.Write(pngData); err != nil {
		tmpFile.Close()
		return fmt.Errorf("failed to write temp file: %w", err)
	}
	tmpFile.Close()
	if err := buildCmd(tmpFile.Name()).Run(); err != nil {
		return fmt.Errorf("clipboard command failed: %w", err)
	}
	return nil
}
