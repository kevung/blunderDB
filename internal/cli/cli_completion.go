package cli

import (
	"flag"
	"fmt"
	"sort"
	"strings"
)

// runCompletion prints a shell completion script for bash, zsh, or fish. Its
// command list comes from handlers(), so a new subcommand is completed as
// soon as it is wired there.
func (cli *CLI) runCompletion(args []string) error {
	completionCmd := flag.NewFlagSet("completion", flag.ContinueOnError)
	completionCmd.Usage = func() {
		fmt.Println("Usage: blunderdb completion <bash|zsh|fish>")
		fmt.Println()
		fmt.Println("Print a shell completion script for the subcommand names to stdout.")
		fmt.Println()
		fmt.Println("Examples:")
		fmt.Println("  # bash: load for the current shell session")
		fmt.Println("  source <(blunderdb completion bash)")
		fmt.Println()
		fmt.Println("  # bash: install system-wide (Debian/Ubuntu/Arch layout)")
		fmt.Println("  blunderdb completion bash | sudo tee /etc/bash_completion.d/blunderdb > /dev/null")
		fmt.Println()
		fmt.Println("  # zsh: install into a directory already on $fpath")
		fmt.Println("  blunderdb completion zsh > \"${fpath[1]}/_blunderdb\"")
		fmt.Println()
		fmt.Println("  # fish: load for the current shell session")
		fmt.Println("  blunderdb completion fish | source")
	}
	if err := completionCmd.Parse(args); err != nil {
		return err
	}
	if completionCmd.NArg() != 1 {
		completionCmd.Usage()
		return fmt.Errorf("expected exactly one shell name: bash, zsh, or fish")
	}

	commands := cli.commandNames()

	switch strings.ToLower(completionCmd.Arg(0)) {
	case "bash":
		fmt.Print(bashCompletionScript(commands))
	case "zsh":
		fmt.Print(zshCompletionScript(commands))
	case "fish":
		fmt.Print(fishCompletionScript(commands))
	default:
		return fmt.Errorf("unknown shell: %s (must be 'bash', 'zsh', or 'fish')", completionCmd.Arg(0))
	}
	return nil
}

// commandNames returns every top-level word blunderdb accepts: the
// handlers() subcommands plus serve, call and migrate, which main.go
// dispatches first but a shell types the same way. Sorted for a stable
// script.
func (cli *CLI) commandNames() []string {
	handlers := cli.handlers()
	names := make([]string, 0, len(handlers)+3)
	for name := range handlers {
		names = append(names, name)
	}
	names = append(names, "serve", "call", "migrate")
	sort.Strings(names)
	return names
}

// bashCompletionScript returns a completion function offering commands as
// the first word after `blunderdb` or `blunderDB` (both names are installed).
func bashCompletionScript(commands []string) string {
	return fmt.Sprintf(`# bash completion for blunderdb — generated by "blunderdb completion bash"
_blunderdb_completions() {
    local cur
    cur="${COMP_WORDS[COMP_CWORD]}"
    if [ "$COMP_CWORD" -eq 1 ]; then
        COMPREPLY=( $(compgen -W "%s" -- "$cur") )
    fi
}
complete -F _blunderdb_completions blunderdb
complete -F _blunderdb_completions blunderDB
`, strings.Join(commands, " "))
}

// zshCompletionScript returns a #compdef completion function.
func zshCompletionScript(commands []string) string {
	return fmt.Sprintf(`#compdef blunderdb blunderDB
# zsh completion for blunderdb — generated by "blunderdb completion zsh"
_blunderdb() {
    local -a commands
    commands=(%s)
    _describe 'command' commands
}
compdef _blunderdb blunderdb
compdef _blunderdb blunderDB
`, strings.Join(commands, " "))
}

// fishCompletionScript returns fish complete(1) directives.
func fishCompletionScript(commands []string) string {
	joined := strings.Join(commands, " ")
	return fmt.Sprintf(`# fish completion for blunderdb — generated by "blunderdb completion fish"
set -l __blunderdb_commands %s
complete -c blunderdb -f -n "not __fish_seen_subcommand_from $__blunderdb_commands" -a "$__blunderdb_commands"
complete -c blunderDB -f -n "not __fish_seen_subcommand_from $__blunderdb_commands" -a "$__blunderdb_commands"
`, joined)
}
